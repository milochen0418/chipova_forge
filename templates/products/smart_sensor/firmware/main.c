/*
 * Smart temperature controller: firmware of the board's MCU (STM32F407, bare metal).
 *
 * Every SAMPLE_MS it reads the temperature sensor (TMP1075 on I2C) and writes the reading into
 * the smart sensor chip, which compares it with the threshold in its own logic. When the chip
 * raises its IRQ pin (an alarm), the interrupt handler marks it and the main loop reports it on
 * the UART and clears it in the chip. The UART also takes commands, one per line:
 *
 *   PING                  -> PONG
 *   INFO                  -> INFO chip=0x534e5331 fw=1.0 sample_ms=100
 *   GET STATUS            -> STATUS temp=4000 threshold=3500 above=1 alarm=0 count=1 enabled=1 hyst=50
 *   SET THRESHOLD <c>     -> OK threshold=<c>         (hundredths of a degree Celsius, signed)
 *   SET HYST <c>          -> OK hyst=<c>
 *   ENABLE <0|1>          -> OK enabled=<0|1>
 *   CLEAR                 -> OK cleared
 *
 * and reports by itself:  READY ...,  ALARM temp=.. threshold=.. count=..,  NORMAL temp=..
 *
 * board.h (where things are on the board) is generated by Chipova Forge from system.yaml,
 * smart_sensor_regs.h (the chip's registers) by PeakRDL-cheader from the chip's SystemRDL, and
 * forge_chip.h reaches the registers whichever way the board wires the chip (here: SPI).
 */
#include <stddef.h>
#include <stdint.h>

#include "board.h"
#include "forge_chip.h"
#include "smart_sensor_regs.h"
#include "stm32f4_min.h"

#define FW_VERSION "1.0"
#define CHIP_ID_EXPECTED 0x534E5331u

/* The chip's registers, by name (offsets from the SystemRDL's C header). */
#define CHIP_RD(field) chip_read(offsetof(smart_sensor_regs_t, field))
#define CHIP_WR(field, v) chip_write(offsetof(smart_sensor_regs_t, field), (uint32_t)(v))

static volatile uint32_t ticks_ms;
static volatile int alarm_pending;

/* ------------------------------------------------------------------ UART */

#define RX_SIZE 128
static volatile char rx_buf[RX_SIZE];
static volatile unsigned rx_head, rx_tail;

static void uart_putc(char c)
{
    while (!(USART_SR(BOARD_UART) & USART_SR_TXE)) {}
    USART_DR(BOARD_UART) = (uint8_t)c;
}

static void uart_puts(const char *s)
{
    while (*s) uart_putc(*s++);
}

static void uart_putint(int32_t v)
{
    char tmp[12];
    int n = 0;
    uint32_t u = v < 0 ? (uint32_t)(-v) : (uint32_t)v;
    if (v < 0) uart_putc('-');
    do { tmp[n++] = (char)('0' + u % 10u); u /= 10u; } while (u);
    while (n) uart_putc(tmp[--n]);
}

static void uart_puthex(uint32_t v)
{
    uart_puts("0x");
    for (int i = 28; i >= 0; i -= 4) uart_putc("0123456789abcdef"[(v >> i) & 0xFu]);
}

static void uart_kv(const char *key, int32_t v)
{
    uart_putc(' ');
    uart_puts(key);
    uart_putc('=');
    uart_putint(v);
}

void BOARD_UART_IRQHandler(void)
{
    if (USART_SR(BOARD_UART) & USART_SR_RXNE) {
        char c = (char)USART_DR(BOARD_UART);
        unsigned next = (rx_head + 1u) % RX_SIZE;
        if (next != rx_tail) {
            rx_buf[rx_head] = c;
            rx_head = next;
        }
    }
}

static int uart_getc(char *c)
{
    if (rx_tail == rx_head) return 0;
    *c = rx_buf[rx_tail];
    rx_tail = (rx_tail + 1u) % RX_SIZE;
    return 1;
}

/* ------------------------------------------------------------------ the sensor (I2C) */

static int i2c_wait(uint32_t flags)
{
    for (uint32_t n = 0; n < 200000u; n++) {
        uint32_t sr = I2C_SR1(BOARD_SENSOR_I2C);
        if (sr & I2C_SR1_AF) return -1;
        if (sr & flags) return 0;
    }
    return -2;
}

/* Reads a 16-bit register of an I2C device: write its pointer, then read two bytes. */
static int i2c_read16(uint8_t addr, uint8_t reg, uint16_t *out)
{
    uint32_t i2c = BOARD_SENSOR_I2C;
    I2C_CR1(i2c) |= I2C_CR1_START;
    if (i2c_wait(I2C_SR1_SB)) goto fail;
    I2C_DR(i2c) = (uint32_t)(addr << 1);
    if (i2c_wait(I2C_SR1_ADDR)) goto fail;
    (void)I2C_SR2(i2c);
    if (i2c_wait(I2C_SR1_TXE)) goto fail;
    I2C_DR(i2c) = reg;
    if (i2c_wait(I2C_SR1_TXE | I2C_SR1_BTF)) goto fail;

    I2C_CR1(i2c) |= I2C_CR1_START;
    if (i2c_wait(I2C_SR1_SB)) goto fail;
    I2C_DR(i2c) = (uint32_t)(addr << 1) | 1u;
    if (i2c_wait(I2C_SR1_ADDR)) goto fail;
    (void)I2C_SR2(i2c);
    if (i2c_wait(I2C_SR1_RXNE)) goto fail;
    uint8_t hi = (uint8_t)I2C_DR(i2c);
    I2C_CR1(i2c) &= ~I2C_CR1_ACK;
    I2C_CR1(i2c) |= I2C_CR1_STOP;
    if (i2c_wait(I2C_SR1_RXNE)) goto fail;
    uint8_t lo = (uint8_t)I2C_DR(i2c);
    I2C_CR1(i2c) |= I2C_CR1_ACK;
    *out = (uint16_t)((hi << 8) | lo);
    return 0;
fail:
    I2C_SR1(i2c) &= ~I2C_SR1_AF;
    I2C_CR1(i2c) |= I2C_CR1_STOP;
    return -1;
}

/* TMP1075 (and TMP108, TMP75): register 0 holds the temperature, 12 bits left-justified, 0.0625 degC per step. */
static int read_temperature(int32_t *centi)
{
    uint16_t raw;
    if (i2c_read16(BOARD_SENSOR_ADDR, 0x00, &raw)) return -1;
    int32_t steps = ((int16_t)raw) >> 4;
    *centi = steps * 625 / 100;
    return 0;
}

/* ------------------------------------------------------------------ the chip */

void BOARD_CHIP_IRQHandler(void)
{
    if (EXTI_PR & (1u << BOARD_CHIP_IRQ_PIN)) {
        EXTI_PR = 1u << BOARD_CHIP_IRQ_PIN;
        alarm_pending = 1;
    }
}

static int32_t s16(uint32_t v) { return (int32_t)(int16_t)(v & 0xFFFFu); }

static void report_status(const char *word)
{
    uint32_t status = CHIP_RD(STATUS);
    uart_puts(word);
    uart_kv("temp", s16(CHIP_RD(TEMP)));
    uart_kv("threshold", s16(CHIP_RD(THRESHOLD)));
    uart_kv("above", (int32_t)(status & SMART_SENSOR_REGS__STATUS__ABOVE_bm ? 1 : 0));
    uart_kv("alarm", (int32_t)(status & SMART_SENSOR_REGS__STATUS__ALARM_bm ? 1 : 0));
    uart_kv("count", (int32_t)(CHIP_RD(COUNT) & 0xFFFFu));
    uart_kv("enabled", (int32_t)(CHIP_RD(CTRL) & SMART_SENSOR_REGS__CTRL__EN_bm ? 1 : 0));
    uart_kv("hyst", s16(CHIP_RD(HYST)));
    uart_puts("\r\n");
}

/* ------------------------------------------------------------------ commands */

static int starts_with(const char *s, const char *prefix)
{
    while (*prefix) {
        char a = *s++, b = *prefix++;
        if (a >= 'a' && a <= 'z') a = (char)(a - 32);
        if (a != b) return 0;
    }
    return 1;
}

static int parse_int(const char *s, int32_t *out)
{
    int neg = 0, any = 0;
    int32_t v = 0;
    while (*s == ' ') s++;
    if (*s == '-' || *s == '+') neg = *s++ == '-';
    while (*s >= '0' && *s <= '9') { v = v * 10 + (*s++ - '0'); any = 1; }
    if (!any || v > 32767) return -1;
    *out = neg ? -v : v;
    return 0;
}

static void handle_line(const char *line)
{
    int32_t v;
    if (starts_with(line, "PING")) {
        uart_puts("PONG\r\n");
    } else if (starts_with(line, "INFO")) {
        uart_puts("INFO chip=");
        uart_puthex(CHIP_RD(ID));
        uart_puts(" fw=" FW_VERSION);
        uart_kv("sample_ms", BOARD_SAMPLE_MS);
        uart_puts("\r\n");
    } else if (starts_with(line, "GET STATUS")) {
        report_status("STATUS");
    } else if (starts_with(line, "SET THRESHOLD")) {
        if (parse_int(line + 13, &v)) { uart_puts("ERR bad value\r\n"); return; }
        CHIP_WR(THRESHOLD, (uint32_t)v & 0xFFFFu);
        uart_puts("OK");
        uart_kv("threshold", s16(CHIP_RD(THRESHOLD)));
        uart_puts("\r\n");
    } else if (starts_with(line, "SET HYST")) {
        if (parse_int(line + 8, &v) || v < 0) { uart_puts("ERR bad value\r\n"); return; }
        CHIP_WR(HYST, (uint32_t)v & 0xFFFFu);
        uart_puts("OK");
        uart_kv("hyst", s16(CHIP_RD(HYST)));
        uart_puts("\r\n");
    } else if (starts_with(line, "ENABLE")) {
        if (parse_int(line + 6, &v) || (v != 0 && v != 1)) { uart_puts("ERR bad value\r\n"); return; }
        uint32_t ctrl = CHIP_RD(CTRL);
        CHIP_WR(CTRL, v ? (ctrl | SMART_SENSOR_REGS__CTRL__EN_bm) : (ctrl & ~SMART_SENSOR_REGS__CTRL__EN_bm));
        uart_puts("OK");
        uart_kv("enabled", v);
        uart_puts("\r\n");
    } else if (starts_with(line, "CLEAR")) {
        CHIP_WR(STATUS, SMART_SENSOR_REGS__STATUS__ALARM_bm);
        uart_puts("OK cleared\r\n");
    } else if (line[0]) {
        uart_puts("ERR unknown command\r\n");
    }
}

/* ------------------------------------------------------------------ set-up */

void SysTick_Handler(void) { ticks_ms++; }

static void gpio_mode(uint32_t port, unsigned pin, uint32_t mode)
{
    GPIO_MODER(port) = (GPIO_MODER(port) & ~(3u << (2 * pin))) | (mode << (2 * pin));
}

static void gpio_af(uint32_t port, unsigned pin, uint32_t af)
{
    gpio_mode(port, pin, 2u);
    if (pin < 8) GPIO_AFRL(port) = (GPIO_AFRL(port) & ~(0xFu << (4 * pin))) | (af << (4 * pin));
    else GPIO_AFRH(port) = (GPIO_AFRH(port) & ~(0xFu << (4 * (pin - 8)))) | (af << (4 * (pin - 8)));
}

static void led(uint32_t port, unsigned pin, int on)
{
    GPIO_BSRR(port) = on ? (1u << pin) : (1u << (pin + 16));
}

static void board_init(void)
{
    /* Clocks: all GPIO ports and SYSCFG (16 MHz HSI, the clock after reset). */
    RCC_AHB1ENR |= 0x1FFu;
    RCC_APB2ENR |= 1u << 14;

    /* LEDs */
    gpio_mode(BOARD_LED_HEARTBEAT_PORT, BOARD_LED_HEARTBEAT_PIN, 1u);
    gpio_mode(BOARD_LED_ALARM_PORT, BOARD_LED_ALARM_PIN, 1u);

    /* The console UART: 115200 8N1, receiving by interrupt */
    BOARD_UART_CLOCK_ON();
    gpio_af(BOARD_UART_TX_PORT, BOARD_UART_TX_PIN, BOARD_UART_AF);
    gpio_af(BOARD_UART_RX_PORT, BOARD_UART_RX_PIN, BOARD_UART_AF);
    USART_BRR(BOARD_UART) = 16000000u / 115200u;
    USART_CR1(BOARD_UART) = USART_CR1_UE | USART_CR1_TE | USART_CR1_RE | USART_CR1_RXNEIE;
    nvic_enable(BOARD_UART_IRQn);

    /* The sensor's I2C, open drain, 100 kHz */
    BOARD_SENSOR_I2C_CLOCK_ON();
    gpio_af(BOARD_SENSOR_SCL_PORT, BOARD_SENSOR_SCL_PIN, BOARD_SENSOR_I2C_AF);
    gpio_af(BOARD_SENSOR_SDA_PORT, BOARD_SENSOR_SDA_PIN, BOARD_SENSOR_I2C_AF);
    GPIO_OTYPER(BOARD_SENSOR_SCL_PORT) |= 1u << BOARD_SENSOR_SCL_PIN;
    GPIO_OTYPER(BOARD_SENSOR_SDA_PORT) |= 1u << BOARD_SENSOR_SDA_PIN;
    I2C_CR2(BOARD_SENSOR_I2C) = 16u;
    I2C_CCR(BOARD_SENSOR_I2C) = 80u;
    I2C_TRISE(BOARD_SENSOR_I2C) = 17u;
    I2C_CR1(BOARD_SENSOR_I2C) = I2C_CR1_PE | I2C_CR1_ACK;

    /* The chip: its interface (SPI or the memory bus), and its IRQ pin as an input with an
     * external interrupt on its rising edge. */
    chip_init();
    gpio_mode(BOARD_CHIP_IRQ_PORT, BOARD_CHIP_IRQ_PIN, 0u);
    SYSCFG_EXTICR(BOARD_CHIP_IRQ_PIN / 4) =
        (SYSCFG_EXTICR(BOARD_CHIP_IRQ_PIN / 4) & ~(0xFu << (4 * (BOARD_CHIP_IRQ_PIN % 4)))) |
        (BOARD_CHIP_IRQ_PORT_INDEX << (4 * (BOARD_CHIP_IRQ_PIN % 4)));
    EXTI_RTSR |= 1u << BOARD_CHIP_IRQ_PIN;
    EXTI_IMR |= 1u << BOARD_CHIP_IRQ_PIN;
    nvic_enable(BOARD_CHIP_IRQn);

    /* 1 ms ticks */
    SYST_RVR = 16000000u / 1000u - 1u;
    SYST_CVR = 0;
    SYST_CSR = 7u;
}

int main(void)
{
    board_init();

    uint32_t id = CHIP_RD(ID);
    if (id != CHIP_ID_EXPECTED) {
        uart_puts("ERROR chip id=");
        uart_puthex(id);
        uart_puts("\r\n");
    }
    CHIP_WR(CTRL, SMART_SENSOR_REGS__CTRL__EN_bm | SMART_SENSOR_REGS__CTRL__IRQ_EN_bm);
    uart_puts("READY smart_sensor chip=");
    uart_puthex(id);
    uart_puts(" fw=" FW_VERSION "\r\n");

    char line[64];
    unsigned len = 0;
    uint32_t next_sample = 0, next_blink = 0;
    int was_above = 0, sensor_ok = 1;

    for (;;) {
        uint32_t now = ticks_ms;

        if ((int32_t)(now - next_sample) >= 0) {
            next_sample = now + BOARD_SAMPLE_MS;
            int32_t centi;
            if (read_temperature(&centi) == 0) {
                CHIP_WR(TEMP, (uint32_t)centi & 0xFFFFu);
                if (!sensor_ok) uart_puts("SENSOR ok\r\n");
                sensor_ok = 1;
            } else if (sensor_ok) {
                uart_puts("ERROR sensor not answering\r\n");
                sensor_ok = 0;
            }
            int above = (CHIP_RD(STATUS) & SMART_SENSOR_REGS__STATUS__ABOVE_bm) != 0;
            led(BOARD_LED_ALARM_PORT, BOARD_LED_ALARM_PIN, above);
            if (was_above && !above) report_status("NORMAL");
            was_above = above;
        }

        if (alarm_pending) {
            alarm_pending = 0;
            report_status("ALARM");
            CHIP_WR(STATUS, SMART_SENSOR_REGS__STATUS__ALARM_bm); /* write 1 to clear */
        }

        if ((int32_t)(now - next_blink) >= 0) {
            next_blink = now + 500u;
            GPIO_ODR(BOARD_LED_HEARTBEAT_PORT) ^= 1u << BOARD_LED_HEARTBEAT_PIN;
        }

        char c;
        while (uart_getc(&c)) {
            if (c == '\r' || c == '\n') {
                line[len] = 0;
                if (len) handle_line(line);
                len = 0;
            } else if (len < sizeof line - 1) {
                line[len++] = c;
            }
        }

        wait_for_interrupt();
    }
}
