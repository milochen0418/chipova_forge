"""A register harness around a chip that has no bus (the contract's interface is ``none``).

The MCU can't reach such a chip's pins directly in the simulation, so Forge puts it inside a
small module with an APB3 register block (generated by PeakRDL-regblock from a SystemRDL file
Forge writes for this chip, so the firmware gets a C header and the SDK a register map too):

    0x00 ID        "FRG1"
    0x04 CONTROL   bit 0 RESET: holds the chip in reset (1 after power-up; the firmware clears it)
    0x08 INPUTS    the chip's input pins, one bit each (the MCU drives them)
    0x0C OUTPUTS   the chip's output pins, one bit each (read only)
    0x10.. EDGES_n rising edges counted on output n (the first four outputs)

The harness's own output pins are the chip's outputs, so the board wires them like any chip's
pins (an LED, an interrupt). It is part of the simulation only: the board's real chip is the
chip itself, and its pins go to the MCU as the board says.
"""

from __future__ import annotations

from chipova_forge.contract.contract import Contract

HARNESS_TOP = "forge_harness"
HARNESS_REGS = "forge_harness_regs"
HARNESS_ID = 0x46524731  # "FRG1"
MAX_EDGES = 4


def _ins(c: Contract) -> list[tuple[str, int]]:
    return [(p.port, p.width) for p in c.inputs]


def _outs(c: Contract) -> list[tuple[str, int]]:
    return [(p.port, p.width) for p in c.pins if p.direction == "out" and p.role in ("irq", "output")]


def check(c: Contract) -> list[str]:
    problems = []
    if sum(w for _, w in _ins(c)) > 32:
        problems.append("the chip's inputs are more than 32 bits: the harness reaches the first 32")
    if sum(w for _, w in _outs(c)) > 32:
        problems.append("the chip's outputs are more than 32 bits: the harness reaches the first 32")
    return problems


def render_rdl(c: Contract) -> str:
    n_in = min(32, sum(w for _, w in _ins(c)))
    n_out = min(32, sum(w for _, w in _outs(c)))
    one_bit_outs = [n for n, w in _outs(c) if w == 1][:MAX_EDGES]
    lines = [
        f"// Generated by Chipova Forge: the register harness around the chip {c.chip.top_module}",
        "// (it has no bus; the MCU reaches its pins through these registers in the simulation).",
        f"addrmap {HARNESS_REGS} {{",
        f'    name = "Forge harness of {c.chip.top_module}";',
        "    default regwidth = 32;",
        "    default accesswidth = 32;",
        "",
        f'    reg {{ name = "Harness ID"; desc = "Reads 0x{HARNESS_ID:08X} (FRG1)."; field {{ sw = r; hw = na; }} VALUE[31:0] = 32\'h{HARNESS_ID:08X}; }} ID @ 0x00;',
        '    reg { name = "Control"; field { sw = rw; hw = r; desc = "Hold the chip in reset (1 after power-up)."; } RESET[0:0] = 1; } CONTROL @ 0x04;',
    ]
    if n_in:
        lines.append(f'    reg {{ name = "Inputs"; desc = "The chip\'s input pins, one bit each."; field {{ sw = rw; hw = r; }} VALUE[{n_in - 1}:0] = 0; }} INPUTS @ 0x08;')
    if n_out:
        lines.append(f'    reg {{ name = "Outputs"; desc = "The chip\'s output pins, one bit each."; field {{ sw = r; hw = w; }} VALUE[{n_out - 1}:0]; }} OUTPUTS @ 0x0C;')
    for i, name in enumerate(one_bit_outs):
        lines.append(f'    reg {{ name = "Rising edges of {name}"; field {{ sw = r; hw = w; }} COUNT[31:0]; }} EDGES_{i} @ 0x{0x10 + 4 * i:02X};')
    lines.append("};")
    return "\n".join(lines) + "\n"


def render_verilog(c: Contract) -> str:
    ins, outs = _ins(c), _outs(c)
    one_bit_outs = [n for n, w in outs if w == 1][:MAX_EDGES]
    reset_expr = "chip_rst_n" if c.reset.active_low else "~chip_rst_n"
    out_ports = "".join(f",\n    output wire {'[' + str(w - 1) + ':0] ' if w > 1 else ''}{n}" for n, w in outs)
    conns = [f"        .{c.clock.port}(clk)", f"        .{c.reset.port}({reset_expr})"]
    bit = 0
    for n, w in ins:
        if bit + w <= 32:
            src = f"hwif_out.INPUTS.VALUE.value[{bit + w - 1}:{bit}]" if w > 1 else f"hwif_out.INPUTS.VALUE.value[{bit}]"
        else:
            src = f"{w}'d0"
        conns.append(f"        .{n}({src})")
        bit += w
    for n, _ in outs:
        conns.append(f"        .{n}({n})")
    packed = []
    bit = 0
    for n, w in outs:
        if bit + w > 32:
            break
        packed.insert(0, n)
        bit += w
    edges = "\n".join(
        f"""    reg [31:0] edges_{i};
    reg        last_{i};
    always @(posedge clk) begin
        if (!rst_n) begin edges_{i} <= 32'd0; last_{i} <= 1'b0; end
        else begin
            last_{i} <= {n};
            if ({n} && !last_{i}) edges_{i} <= edges_{i} + 32'd1;
        end
    end
    assign hwif_in.EDGES_{i}.COUNT.next = edges_{i};"""
        for i, n in enumerate(one_bit_outs)
    )
    outputs_assign = f"    assign hwif_in.OUTPUTS.VALUE.next = {{{', '.join(packed)}}};" if packed else ""
    conns_text = ",\n".join(conns)
    return f"""// Generated by Chipova Forge: the register harness around the chip {c.chip.top_module}, for the
// simulation (the chip has no bus). See chipova_forge/cosim/harness.py for its registers.
module {HARNESS_TOP} (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        psel,
    input  wire        penable,
    input  wire        pwrite,
    input  wire [7:0]  paddr,
    input  wire [31:0] pwdata,
    output wire        pready,
    output wire [31:0] prdata,
    output wire        pslverr{out_ports}
);
    import {HARNESS_REGS}_pkg::*;
    {HARNESS_REGS}__in_t  hwif_in;
    {HARNESS_REGS}__out_t hwif_out;

    {HARNESS_REGS} regs (
        .clk           (clk),
        .rst           (~rst_n),
        .s_apb_psel    (psel),
        .s_apb_penable (penable),
        .s_apb_pwrite  (pwrite),
        .s_apb_paddr   (paddr[{_addr_bits()}:0]),
        .s_apb_pwdata  (pwdata),
        .s_apb_pready  (pready),
        .s_apb_prdata  (prdata),
        .s_apb_pslverr (pslverr),
        .hwif_in       (hwif_in),
        .hwif_out      (hwif_out)
    );

    wire chip_rst_n = rst_n & ~hwif_out.CONTROL.RESET.value;

    {c.chip.top_module} chip (
{conns_text}
    );

{outputs_assign}
{edges}
endmodule
"""


def _addr_bits() -> int:
    return 4  # 0x00..0x1F: five address bits


def contract_ports() -> dict[str, str]:
    """The harness's APB3 ports (for the co-simulation spec)."""
    return {"psel": "psel", "penable": "penable", "pwrite": "pwrite", "paddr": "paddr", "pwdata": "pwdata",
            "prdata": "prdata", "pready": "pready", "pslverr": "pslverr"}
